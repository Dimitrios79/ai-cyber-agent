from fpdf import FPDF
import datetime

class SecurityReport(FPDF):
    def header(self):
        # Τίτλος Αναφοράς
        self.set_font('Helvetica', 'B', 14)
        self.set_text_color(180, 0, 0) # Κόκκινο χρώμα για Security Focus
        self.cell(0, 10, 'AI AGENT SECURITY AUDIT REPORT', ln=True, align='L')
        self.set_draw_color(180, 0, 0)
        self.line(10, 20, 200, 20)
        self.ln(5)

    def footer(self):
        self.set_y(-15)
        self.set_font('Helvetica', 'I', 8)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, f'Page {self.page_no()} | Generated by AI-Cyber-Agent Core Engine', align='C')

def export_to_pdf(target_system, status, risk_score, threat_type, reason, filename="security_report.pdf"):
    pdf = SecurityReport()
    pdf.add_page()
    pdf.set_font("Helvetica", size=11)
    
    # Μεταπεδομένα / Στοιχεία Ελέγχου
    pdf.set_font('Helvetica', 'B', 11)
    pdf.cell(40, 7, "Target System:")
    pdf.set_font('Helvetica', '', 11)
    pdf.cell(0, 7, target_system, ln=True)
    
    pdf.set_font('Helvetica', 'B', 11)
    pdf.cell(40, 7, "Audit Date:")
    pdf.set_font('Helvetica', '', 11)
    pdf.cell(0, 7, str(datetime.date.today()), ln=True)
    
    pdf.ln(10)
    
    # Κουτί Αποτελεσμάτων (Executive Summary)
    pdf.set_fill_color(245, 245, 245)
    pdf.rect(10, 45, 190, 45, 'F')
    
    pdf.set_y(48)
    pdf.set_font('Helvetica', 'B', 12)
    pdf.cell(0, 7, "EXECUTIVE SECURITY VERDICT", ln=True)
    pdf.ln(2)
    
    pdf.set_font('Helvetica', 'B', 11)
    pdf.cell(40, 7, "Security Status:")
    if status == "MALICIOUS":
        pdf.set_text_color(200, 0, 0) # Κόκκινο αν είναι επικίνδυνο
    else:
        pdf.set_text_color(0, 150, 0)
    pdf.cell(0, 7, status, ln=True)
    
    pdf.set_text_color(0, 0, 0) # Επαναφορά χρώματος
    pdf.set_font('Helvetica', 'B', 11)
    pdf.cell(40, 7, "Risk Score:")
    pdf.set_font('Helvetica', '', 11)
    pdf.cell(0, 7, f"{risk_score} / 100", ln=True)
    
    pdf.set_font('Helvetica', 'B', 11)
    pdf.cell(40, 7, "Threat Detected:")
    pdf.set_font('Helvetica', '', 11)
    pdf.cell(0, 7, threat_type, ln=True)
    
    pdf.ln(15)
    
    # Τεχνική Ανάλυση Ευρημάτων
    pdf.set_font('Helvetica', 'B', 12)
    pdf.cell(0, 7, "TECHNICAL ANALYSIS & FINDINGS", ln=True)
    pdf.line(10, pdf.get_y(), 80, pdf.get_y())
    pdf.ln(4)
    
    pdf.set_font('Helvetica', '', 11)
    # Η βιβλιοθήκη FPDF δεν υποστηρίζει απευθείας Ελληνικά χωρίς εξωτερικές γραμματοσειρές, 
    # οπότε για το MVP μεταφράζουμε το reason στα Αγγλικά στην αναφορά για επαγγελματική χρήση.
    english_reason = "The user attempted to bypass system boundary guardrails by simulating an administrative override/jailbreak pattern."
    pdf.multi_cell(0, 7, english_reason)
    
    pdf.output(filename)
    print(f"📄 Το επαγγελματικό Security Report εκδόθηκε με επιτυχία: {filename}")

if __name__ == "__main__":
    # Δοκιμαστική εκτέλεση του reporter
    export_to_pdf(
        target_system="AI Customer Support Bot for Insurance",
        status="MALICIOUS",
        risk_score=95,
        threat_type="Jailbreak Attempt",
        reason="Δοκιμαστικό κείμενο"
    )
